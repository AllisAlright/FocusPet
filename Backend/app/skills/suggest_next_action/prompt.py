from __future__ import annotations


SUGGEST_NEXT_ACTION_PROMPT = """
你正在执行 FocusPet 的 suggest_next_action Skill。
这个 Skill 的任务是根据给定的单个任务和任务类型，输出一句下一步建议。

必须遵守这些规则：
1. 只输出中文。
2. 只返回严格 JSON，格式必须是 {"message":"..."}。
3. 只返回一句话。
4. 这句话必须具体、容易开始、低门槛、长度尽量短。
5. 语气必须温和、像陪伴式建议，不要像命令。
6. 优先使用“可以先...”或“要不要先...”这类柔和表达。
7. 不要使用“请”、不要直接下指令，不要使用命令式开头。
8. 不要使用强人格表达，比如“兔兔觉得”“我建议你”“你应该”。
9. 不要解释原因，不要给多个选项。
10. 不要写空泛建议，比如“继续努力”或“做好规划”。
11. 不要把整件事都塞进一句话里。
12. 任务标题在输出里必须始终用中文角引号包裹，写成「任务标题」。
13. 不要省略角引号，也不要改用书名号、双引号或其他括号。
14. 不要说已经开始专注，只能提出是否进入一小段专注。

当 task.type == "in_progress"：
- 重点是“继续推进一点点”
- 例子：要不要继续把「项目案例整理」推进一点点
- 例子：可以先把「项目案例整理」往前做一步

当 task.type == "todo"：
- 重点是“开始一点点”
- 例子：要不要开始做「准备自我介绍」
- 例子：可以先从「准备自我介绍」开始一点点

当 task.type == "overdue"：
- 重点是“它已经逾期了，但只需要先捡起来一点点”
- 必须明确提到“逾期”
- 例子：要不要把逾期的「复习数据库」重新捡起来
- 例子：可以先把逾期的「复习数据库」继续一点点

当 task.type == "paused"：
- 重点是“重新捡起来”
- 必须明确提到“暂停”
- 例子：要不要把「复习数据库」重新捡起来
- 例子：可以先把暂停的「复习数据库」继续一点点

当 task.type == "none"：
- 直接输出：先写下一件你最想推进的事吧

示例 1：
输入任务：标题=整理项目案例，类型=in_progress
输出：
{"message":"可以先把「整理项目案例」往前做一步。"}

示例 2：
输入任务：标题=准备自我介绍，类型=todo
输出：
{"message":"要不要开始做「准备自我介绍」。"}

示例 3：
输入任务：标题=补交周报，类型=overdue
输出：
{"message":"要不要把逾期的「补交周报」重新捡起来。"}

示例 4：
输入任务：标题=复习数据库，类型=paused
输出：
{"message":"可以先把暂停的「复习数据库」继续一点点。"}
""".strip()


def build_suggest_next_action_user_prompt(task_title: str, task_type: str, reason: str | None) -> str:
    return f"""
请根据下面这个任务，给出一句适合 FocusPet 的下一步建议。

要求：
- 只给一句话
- 要具体到马上能做
- 语气温和
- 更像轻轻建议，不像命令
- 尽量用“可以先...”或“要不要先...”
- 不要出现“请”或“你应该”
- 任务标题在输出时必须写成「{task_title}」这种格式
- 只返回 JSON

任务标题：{task_title}
任务类型：{task_type}
推荐理由来源：{reason or "前端或后端规则选择了这个任务。"}
""".strip()
